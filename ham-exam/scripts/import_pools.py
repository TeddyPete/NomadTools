"""Copies the official NCVEC question pools from the Ask Elmer repo into the app.

  python3 scripts/import_pools.py ../../askelmer [--explanations]

Reads packs/ham-radio/pack.json and, for each exam's current pool,
questions.json and syllabus.json (generated by Ask Elmer's
tools/parse_ncvec_pool.py from the NCVEC files). Question text, choices,
answer keys and rule references are copied exactly; nothing is reworded.
Deleted questions (NCVEC errata) are kept with their status so history
stays intact, and the app never draws them. Every file keeps its pool_id.

Figures are scaled to 640 px wide PNGs (the app shows them at 1x and 2x).

--explanations also writes data/<pool_id>.explain.json with the answer
summary, method and example for each question from content/*.json.
"""
from __future__ import annotations

import glob
import json
import os
import sys

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "hamexam", "data")
SHORT = {"technician": "Tech", "general": "General", "extra": "Extra"}


def scale_figure(src: str, dst: str, width: int = 640) -> None:
    import numpy as np
    import pygame
    img = pygame.image.load(src)
    # trim the white margin so the diagram fills the small screen
    a = pygame.surfarray.array3d(img).min(axis=2)
    ys, xs = np.nonzero((a < 200).T)
    if len(xs):
        pad = 12
        x0, y0 = max(0, xs.min() - pad), max(0, ys.min() - pad)
        x1, y1 = min(img.get_width(), xs.max() + pad), min(img.get_height(), ys.max() + pad)
        img = img.subsurface((x0, y0, x1 - x0, y1 - y0)).copy()
    w, h = img.get_size()
    if w > width:
        img = pygame.transform.smoothscale(img.convert_alpha() if pygame.display.get_init() else img,
                                           (width, round(h * width / w)))
    pygame.image.save(img, dst)


def main(argv) -> int:
    if not argv:
        print(__doc__)
        return 2
    root = argv[0]
    explain = "--explanations" in argv
    pack_dir = os.path.join(root, "packs", "ham-radio")
    pack = json.load(open(os.path.join(pack_dir, "pack.json")))
    os.makedirs(os.path.join(DATA, "figures"), exist_ok=True)
    index = []
    for ex in pack["exams"]:
        pool = next(p for p in ex["pools"] if p.get("status") == "current")
        pid = pool["pool_id"]
        pdir = os.path.join(pack_dir, pool["path"])
        q = json.load(open(os.path.join(pdir, "questions.json")))
        s = json.load(open(os.path.join(pdir, "syllabus.json")))
        assert q["pool_id"] == pid and s["pool_id"] == pid, pid
        out = {
            "pool_id": pid,
            "exam_id": ex["exam_id"],
            "name": ex["name"],
            "short": SHORT.get(ex["exam_id"], ex["name"].split()[0]),
            "element": ex["fcc_element"],
            "questions_per_exam": ex["questions_per_exam"],
            "passing_score": ex["passing_score"],
            "draw_rule": ex["draw_rule"],
            "effective_from": pool["effective_from"],
            "effective_to": pool["effective_to"],
            "source": q["source"],
            "subelements": [{"id": se["id"], "title": se["title"], "exam_questions": se["exam_questions"],
                             "groups": [{"id": g["id"], "topics": g["topics"]} for g in se["groups"]]}
                            for se in s["subelements"]],
            "questions": [{k: qq[k] for k in ("id", "subelement", "group", "stem", "choices", "answer",
                                               "references", "figures", "status")} for qq in q["questions"]],
        }
        with open(os.path.join(DATA, f"{pid}.json"), "w") as fh:
            json.dump(out, fh, ensure_ascii=False, separators=(",", ":"))
        figs = sorted({f for qq in q["questions"] for f in qq["figures"]})
        for f in figs:
            src = next(iter(glob.glob(os.path.join(pdir, "figures", f + ".*"))), None)
            if src:
                scale_figure(src, os.path.join(DATA, "figures", f + ".png"))
            else:
                print(f"  ! figure {f} not found", file=sys.stderr)
        n_ex = 0
        if explain:
            ex_out = {"pool_id": pid, "questions": {}}
            for cf in sorted(glob.glob(os.path.join(pdir, "content", "*.json"))):
                c = json.load(open(cf))
                assert c["pool_id"] == pid, cf
                for qid, e in c["questions"].items():
                    x = e.get("explanation") or {}
                    ex_out["questions"][qid] = {"concept": e.get("concept", ""),
                                                "answer_summary": x.get("answer_summary", ""),
                                                "method": x.get("method", []),
                                                "example": x.get("example", ""),
                                                "review_status": e.get("review_status", "")}
            n_ex = len(ex_out["questions"])
            with open(os.path.join(DATA, f"{pid}.explain.json"), "w") as fh:
                json.dump(ex_out, fh, ensure_ascii=False, separators=(",", ":"))
        active = sum(1 for qq in q["questions"] if qq["status"] == "active")
        print(f"{pid}: {active} active questions, {len(figs)} figures" + (f", {n_ex} explanations" if explain else ""))
        index.append({"exam_id": ex["exam_id"], "pool_id": pid, "name": ex["name"]})
    with open(os.path.join(DATA, "index.json"), "w") as fh:
        json.dump({"pack_id": pack["pack_id"], "exams": index}, fh, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
